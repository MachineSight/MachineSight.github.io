#!/usr/bin/env python3
"""Fetch available GA4 pageviews and write them in Jekyll data format."""

import json
import os
import re
from pathlib import Path

import yaml
from google.analytics.data_v1beta import BetaAnalyticsDataClient
from google.analytics.data_v1beta.types import DateRange, Dimension, Metric, RunReportRequest
from google.oauth2 import service_account


ROOT = Path(__file__).resolve().parents[1]
POSTS_DIR = ROOT / "_posts"
OUTPUT_PATH = ROOT / "_data" / "pageviews.yml"


def load_front_matter(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    match = re.match(r"\A---\s*\n(.*?)\n---\s*\n", text, re.DOTALL)
    if not match:
        return {}
    return yaml.safe_load(match.group(1)) or {}


def post_url(path: Path, front_matter: dict) -> str:
    if front_matter.get("permalink"):
        return str(front_matter["permalink"])

    match = re.match(r"(\d{4})-(\d{2})-(\d{2})-(.+)\.[^.]+$", path.name)
    if not match:
        raise ValueError(f"Cannot determine URL for {path.name}")
    year, month, day, slug = match.groups()
    return f"/{year}/{month}/{day}/{slug}.html"


def normalize_path(value: str) -> str:
    path = value.split("?", 1)[0].split("#", 1)[0]
    if not path.startswith("/"):
        path = f"/{path}"
    return path.rstrip("/") or "/"


def credentials_from_environment():
    key = os.environ.get("GA_SERVICE_ACCOUNT_KEY")
    if not key:
        raise RuntimeError("GA_SERVICE_ACCOUNT_KEY is not set")
    try:
        info = json.loads(key)
    except json.JSONDecodeError as error:
        raise RuntimeError("GA_SERVICE_ACCOUNT_KEY must contain service-account JSON") from error
    return service_account.Credentials.from_service_account_info(info)


def fetch_pageviews() -> dict[str, int]:
    property_id = os.environ.get("GA_PROPERTY_ID")
    if not property_id:
        raise RuntimeError("GA_PROPERTY_ID is not set")

    client = BetaAnalyticsDataClient(credentials=credentials_from_environment())
    request = RunReportRequest(
        property=f"properties/{property_id}",
        date_ranges=[DateRange(start_date="2025-12-23", end_date="today")],
        dimensions=[Dimension(name="pagePath")],
        metrics=[Metric(name="screenPageViews")],
        limit=100000,
    )
    response = client.run_report(request)
    return {
        normalize_path(row.dimension_values[0].value): int(row.metric_values[0].value)
        for row in response.rows
    }


def main() -> None:
    pageviews = fetch_pageviews()
    output = {}
    for path in sorted(POSTS_DIR.glob("*.markdown")):
        front_matter = load_front_matter(path)
        url = normalize_path(post_url(path, front_matter))
        output[url] = pageviews.get(url, 0)

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(
        "# Generated by scripts/fetch_pageviews.py\n"
        + yaml.safe_dump(output, sort_keys=True, default_flow_style=False),
        encoding="utf-8",
    )
    print(f"Wrote {len(output)} post view counts to {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
